local function read_wal_colors(path)
    local colors = {}
    local file = io.open(path, "r")
    if not file then
        return colors
    end

    for line in file:lines() do
        local name, value = line:match("^%s*%$(%S+)%s*=%s*(%S+)")
        if name and value then
            colors[name] = value
        end
    end
    file:close()

    return colors
end

